#!/usr/bin/env node
/**
 * Generates the values for the admin environment variables.
 *
 *   node scripts/hash-password.js "your-password-here"
 *
 * Paste the output into Vercel > Project > Settings > Environment Variables.
 * The password itself is never stored anywhere -- only the scrypt hash, which
 * cannot be reversed back into the password.
 *
 * Run this locally, not in CI: shell history and CI logs both retain
 * arguments. Clear it from your history afterwards if you are cautious
 * (`history -d` in bash, or prefix the command with a space in most shells).
 */
const { scryptSync, randomBytes } = require('node:crypto')

const password = process.argv[2]

if (!password) {
  console.error('Usage: node scripts/hash-password.js "your-password"')
  process.exit(1)
}

if (password.length < 12) {
  console.error(
    `\n  Refusing: that password is ${password.length} characters.\n` +
      '  This is the only credential guarding file upload on a public site,\n' +
      '  and there is exactly one account to attack. Use 16+ characters, or\n' +
      '  better, a passphrase of four or five unrelated words.\n'
  )
  process.exit(1)
}

const SCRYPT_OPTS = { N: 32768, r: 8, p: 1, maxmem: 96 * 1024 * 1024 }

const salt = randomBytes(16)
const hash = scryptSync(password, salt, 64, SCRYPT_OPTS)

console.log('\nAdd these to your Vercel environment variables:\n')
console.log(`ADMIN_USERNAME=<pick a username>`)
// ':' not '$' — Next.js expands $VARIABLE inside .env files, which would
// silently gut a '$'-delimited hash and break login with no error.
console.log(`ADMIN_PASSWORD_HASH=scrypt:${salt.toString('hex')}:${hash.toString('hex')}`)
console.log(`ADMIN_SESSION_SECRET=${randomBytes(48).toString('base64')}`)
console.log(
  '\nAlso required, from Vercel > Storage > Blob:\n' +
    'BLOB_READ_WRITE_TOKEN=<generated by Vercel when you create the store>\n'
)
console.log('Do NOT commit any of these. .env*.local is already gitignored.\n')
